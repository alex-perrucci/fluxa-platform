function Write-Base64File {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string] $Path,

        [Parameter(Mandatory)]
        [string] $Base64,

        [switch] $DryRun
    )

    if ($DryRun) {
        Write-Host "[DryRun] Scriverebbe: $Path"
        return
    }

    $directory = Split-Path -Path $Path -Parent

    if (-not (Test-Path -LiteralPath $directory)) {
        New-Item -ItemType Directory -Path $directory -Force | Out-Null
    }

    $normalizedBase64 = $Base64 -replace '\s', ''
    $bytes = [Convert]::FromBase64String($normalizedBase64)
    [System.IO.File]::WriteAllBytes($Path, $bytes)
    Write-Host "File scritto: $Path"
}

